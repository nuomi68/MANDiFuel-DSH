"""Sequential Optuna search with a durable sampler and pending evaluation.

Checkpoints contain Python pickle data generated by this controller. Load only
the trusted checkpoint belonging to the current local task.
"""
from __future__ import annotations

import math
import os
from pathlib import Path
import pickle
from typing import Callable


def run_optuna(study, *, suggest: Callable, objective: Callable,
               budget: int, sampler, direction: str = 'minimize',
               checkpoint: str = 'optimizer-state.pkl'):
    """Return the native optimizer after ``budget`` sequential trial evaluations.

``suggest(trial)`` returns the task parameter dictionary. The controller assigns
a unique ``id`` and ``trial`` index. ``objective(point, response)`` returns one
finite scalar. A component-based Study must bind ``progress`` before dispatch.
Solver/report failures stop for repair. Resuming reuses the pending result and
the saved native sampler state without requesting the parameters a second time.
No automatic duplicate suppression, penalties or solver retries are inserted.
    """
    import optuna

    if not isinstance(budget, int) or isinstance(budget, bool) or budget < 1:
        raise ValueError('budget must be a positive integer')
    if study.evaluate is None and not callable(study.progress):
        raise ValueError('Adaptive optimization requires Study(progress=extract_progress)')
    path = (study.root / checkpoint).resolve()
    if not path.is_relative_to(study.root) or path == study.root:
        raise ValueError('checkpoint must be a file inside the current study root')
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists():
        with path.open('rb') as stream:
            state = pickle.load(stream)
        if state.get('schema') != 1 or state['budget'] != budget or state['direction'] != direction:
            raise ValueError('Checkpoint settings differ from the requested search')
        optimizer = state['optimizer']
    else:
        if study.history:
            raise ValueError('Retained evaluations require their original optimizer checkpoint')
        optimizer = optuna.create_study(direction=direction, sampler=sampler)
        state = dict(schema=1, budget=budget, direction=direction,
                     optimizer=optimizer, pending=None)

    def save():
        temp = path.with_name(path.name + '.tmp')
        with temp.open('wb') as stream:
            pickle.dump(state, stream, protocol=pickle.HIGHEST_PROTOCOL)
            stream.flush()
            os.fsync(stream.fileno())
        temp.replace(path)

    save()
    while True:
        complete = [t for t in optimizer.trials if t.state == optuna.trial.TrialState.COMPLETE]
        if len(complete) >= budget:
            return optimizer
        if state['pending'] is None:
            trial = optimizer.ask()
            point = dict(suggest(trial))
            if 'id' in point or 'trial' in point:
                raise ValueError('suggest returns parameters only; controller owns id and trial')
            point.update(id=f't{trial.number:03d}', trial=trial.number)
            state['pending'] = dict(trial=trial.number, handle=trial, point=point)
            save()  # Save parameters and the advanced RNG before starting OFFBEAT.
        pending = state['pending']
        point = pending['point']
        history = study.run([point], workers=1)
        record = next(r for r in history if r['point'] == point)
        if record['status'] != 'completed' or record.get('response') is None:
            raise RuntimeError(f'Evaluation {point["id"]} needs repair; checkpoint retained')
        value = float(objective(point, record['response']))
        if not math.isfinite(value):
            raise ValueError('Objective must be a finite scalar')
        trial = pending['handle']
        trial.set_user_attr('response', record['response'])
        trial.set_user_attr('result_root', record.get('result_root'))
        optimizer.tell(trial, value)
        state['pending'] = None
        save()
