#!/usr/bin/env python3
"""Summarize observable DSH actions without exporting reasoning or response bodies.

Usage: python3 summarize_traces.py /path/to/paired-run
Safe to rerun while a run is active: incomplete trailing JSONL rows are skipped.
"""

import argparse
from collections import Counter
from datetime import datetime, timezone
import json
from pathlib import Path
import re


def compact(value, limit=240):
    """Bound observable argument/error excerpts, redacting common secret forms."""
    text = value if isinstance(value, str) else json.dumps(value, ensure_ascii=False)
    text = re.sub(r"(?i)\b(?:sk|sk-proj)-[a-z0-9_-]{12,}", "<redacted>", text)
    text = re.sub(r"(?i)(bearer\s+)[^\s\"']+", r"\1<redacted>", text)
    text = re.sub(
        r"(?i)((?:api[_-]?key|secret|password|access[_-]?token)\s*[=:]\s*)[^\s,;]+",
        r"\1<redacted>", text,
    )
    text = " ".join(text.split())
    return text if len(text) <= limit else text[:limit - 1] + "…"


def argument_preview(raw):
    try:
        args = json.loads(raw) if isinstance(raw, str) else raw
    except (ValueError, TypeError):
        return compact(raw)
    if not isinstance(args, dict):
        return compact(args)
    # Show filenames and actual commands, never large file bodies or code blocks.
    keys = ("description", "skill", "name", "file_path", "path", "pattern",
            "command", "workdir", "job_id", "task_id", "agent_id", "offset", "limit")
    selected = {key: compact(args[key], 150) for key in keys if key in args}
    for key in args.keys() - selected.keys():
        if re.search(r"key|secret|password|token", key, re.I):
            selected[key] = "<redacted>"
        elif key in {"code", "content", "text", "new_string", "old_string", "prompt"}:
            selected[key] = f"<{len(str(args[key]))} characters>"
        else:
            selected[key] = compact(args[key], 100)
    return compact(selected, 320)


def read_json(path):
    if not path.exists():
        return {}
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {"read_warning": "unreadable or incomplete JSON"}


def utc_timestamp(value):
    if not isinstance(value, (int, float)):
        return None
    return datetime.fromtimestamp(value / 1000, timezone.utc).isoformat()


def blocks(content):
    """Walk only tool-result containers; never descend into reasoning blocks."""
    for block in content if isinstance(content, list) else []:
        if not isinstance(block, dict):
            continue
        yield block
        if block.get("type") == "tool-result":
            yield from blocks(block.get("content", []))


def result_status(data):
    message = data.get("message", {})
    content = list(blocks(message.get("content", [])))
    tool_error = bool(data.get("error")) or any(b.get("isError") is True for b in content)
    text = "\n".join(b.get("text", "") for b in content if b.get("type") == "text")
    # This marker is generated by the Bash tool; arbitrary 'error' text is not
    # counted as a failure because successful reads often contain source code.
    exit_codes = [int(code) for code in re.findall(r"\[exit code:\s*(-?\d+)\]", text)]
    failed = tool_error or any(code != 0 for code in exit_codes) or bool(re.search(r"\[timed out after \d+ms\]|\[killed by signal:", text))
    error = data.get("error", {})
    code = error.get("code") if isinstance(error, dict) else None
    preview = None
    if failed:
        lines = [line.strip() for line in text.splitlines() if line.strip()]
        preview = compact(lines[0], 200) if lines else compact(error, 200)
    return {
        "status": "failed" if failed else "returned",
        "tool_error": tool_error,
        "exit_codes": exit_codes,
        "error_code": code,
        "error_preview": preview,
    }


def session_summary(path, root):
    header = {}
    counts = Counter()
    usage = Counter()
    usage_messages = 0
    messages = 0
    routes = set()
    calls = {}
    events = []
    warnings = []
    times = []
    inherited_skipped = 0
    last_turn_end = None
    with path.open(encoding="utf-8") as stream:
        for line_number, line in enumerate(stream, 1):
            try:
                event = json.loads(line)
            except ValueError:
                warnings.append(f"line {line_number}: invalid/incomplete JSON skipped")
                continue
            if not isinstance(event, dict):
                warnings.append(f"line {line_number}: non-object row skipped")
                continue
            kind = event.get("type", "unknown")
            if kind == "session":
                header = event
                continue
            if event.get("seq", 0) < header.get("seedLength", 0):
                inherited_skipped += 1
                continue
            counts[kind] += 1
            stamp = event.get("time")
            if isinstance(stamp, (int, float)):
                times.append(stamp)
            data = event.get("data", {})
            if not isinstance(data, dict):
                continue
            if kind in {"request/header", "request/context"}:
                route = data.get("header", data)
                if route.get("provider") and route.get("model"):
                    routes.add((route["provider"], route["model"]))
            elif kind == "assistant/message":
                messages += 1
                route = data.get("message", {}).get("source", {})
                if route.get("provider") and route.get("model"):
                    routes.add((route["provider"], route["model"]))
                if isinstance(data.get("usage"), dict):
                    usage_messages += 1
                    usage.update({k: v for k, v in data["usage"].items()
                                  if isinstance(v, (int, float)) and not isinstance(v, bool)})
            elif kind == "tool/call":
                call_id = data.get("callId", f"seq-{event.get('seq')}")
                call = {
                    "call_id": call_id, "session_id": header.get("id", path.parent.name),
                    "turn": data.get("turn"), "step": data.get("step"),
                    "seq": event.get("seq"), "started_at_ms": stamp,
                    "started_at_utc": utc_timestamp(stamp),
                    "name": data.get("name", "unknown"),
                    "arguments_preview": argument_preview(data.get("arguments", {})),
                    "status": "pending", "tool_error": False, "exit_codes": [],
                }
                calls[call_id] = call
                events.append(call)
            elif kind == "tool/result":
                call_id = data.get("message", {}).get("source", {}).get("callId")
                if call_id not in calls:
                    warnings.append(f"seq {event.get('seq')}: unmatched tool result")
                    continue
                call = calls[call_id]
                call.update(result_status(data))
                call["result_seq"] = event.get("seq")
                call["result_at_utc"] = utc_timestamp(stamp)
                if isinstance(stamp, (int, float)) and isinstance(call["started_at_ms"], (int, float)):
                    call["recorded_duration_seconds"] = round((stamp - call["started_at_ms"]) / 1000, 3)
            elif kind == "turn/end":
                reason = data.get("reason", {})
                last_turn_end = {
                    "turn": data.get("turn"), "time_utc": utc_timestamp(stamp),
                    "kind": reason.get("kind") if isinstance(reason, dict) else str(reason),
                }
                if isinstance(reason, dict) and reason.get("error"):
                    last_turn_end["error"] = compact(reason["error"], 300)
    by_name = Counter(call["name"] for call in events)
    return {
        "path": str(path.relative_to(root)), "session_id": header.get("id", path.parent.name),
        "parent_session": header.get("parentSession"), "cwd": header.get("cwd"),
        "delegation_depth": header.get("delegationDepth", 0),
        "inherited_events_excluded": inherited_skipped,
        "routes": [{"provider": p, "model": m} for p, m in sorted(routes)],
        "event_counts": dict(sorted(counts.items())),
        "steps_started": counts["step/start"], "steps_completed": counts["step/end"],
        "assistant_messages": messages, "usage_messages": usage_messages,
        "tokens": dict(sorted(usage.items())),
        "tool_calls": len(events), "tools_by_name": dict(sorted(by_name.items())),
        "tool_failures": sum(c["status"] == "failed" for c in events),
        "tool_error_results": sum(c["tool_error"] for c in events),
        "pending_tools": sum(c["status"] == "pending" for c in events),
        "first_event_at_utc": utc_timestamp(min(times)) if times else None,
        "last_event_at_utc": utc_timestamp(max(times)) if times else None,
        "observed_span_seconds": round((max(times) - min(times)) / 1000, 3) if times else None,
        "last_turn_end": last_turn_end, "warnings": warnings, "timeline": events,
    }


def arm_summary(root, arm):
    arm_root = root / arm
    sessions = [session_summary(path, root) for path in sorted((arm_root / "traces").rglob("session.jsonl"))]
    run = read_json(arm_root / "run.json")
    by_name, usage = Counter(), Counter()
    routes = set()
    timeline = []
    for session in sessions:
        by_name.update(session["tools_by_name"])
        usage.update(session["tokens"])
        routes.update((r["provider"], r["model"]) for r in session["routes"])
        timeline.extend(session["timeline"])
    timeline.sort(key=lambda c: (c.get("started_at_ms") or 0, c["session_id"], c.get("seq") or 0))
    status = "missing"
    if run:
        status = "running" if "exit_code" not in run else ("completed" if run["exit_code"] == 0 else "failed")
        if run.get("timed_out"):
            status = "timed_out"
    return {
        "arm": arm, "run_status": status, "run": run,
        "session_count": len(sessions),
        "routes": [{"provider": p, "model": m} for p, m in sorted(routes)],
        **{key: sum(s[key] for s in sessions) for key in (
            "steps_started", "steps_completed", "assistant_messages", "usage_messages",
            "tool_calls", "tool_failures", "tool_error_results", "pending_tools")},
        "tools_by_name": dict(sorted(by_name.items())), "tokens": dict(sorted(usage.items())),
        "sessions": sessions, "timeline": timeline,
    }


def markdown_cell(value):
    return str(value).replace("|", "\\|").replace("\n", " ").replace("`", "'")


def markdown(summary):
    lines = ["# DSH 双路可观察执行轨迹", "", f"运行目录：`{summary['run_root']}`", "",
             "仅汇总工具调用、返回状态、会话元数据和用量；不包含模型推理正文。", "",
             "| 指标 | bare | skill |", "| --- | ---: | ---: |"]
    bare, skill = summary["arms"]["bare"], summary["arms"]["skill"]
    for label, key in (("运行状态", "run_status"), ("会话数", "session_count"),
                       ("开始的步骤", "steps_started"), ("完成的步骤", "steps_completed"),
                       ("工具调用", "tool_calls"), ("工具/命令失败", "tool_failures"),
                       ("其中工具异常标记", "tool_error_results"), ("待返回工具", "pending_tools")):
        lines.append(f"| {label} | {bare[key]} | {skill[key]} |")
    for label, key in (("总 token（供应方报告）", "totalTokens"),
                       ("非缓存输入 token", "inputTokens"), ("缓存读取 token", "cacheReadTokens"),
                       ("输出 token", "outputTokens")):
        lines.append(f"| {label} | {bare['tokens'].get(key, '未报告')} | {skill['tokens'].get(key, '未报告')} |")
    lines.extend(["", "用量仅累加新产生的 `assistant/message.data.usage`，不重复累加流式 chunk；"
                  "子会话继承的前缀按 `seedLength` 排除。输入 token 与缓存读取 token 分列，"
                  "reasoningTokens 是输出的子集，不应额外加到总量。未报告的调用费用不作估算。", "",
                  "工具状态 `returned` 仅表示未报告工具异常或命令非零退出，不等于工程结果正确。"
                  "耗时为调用事件到持久化结果事件的间隔，含排队/记录时间，不能直接相加为墙钟时间。"])
    for name in ("bare", "skill"):
        arm = summary["arms"][name]
        routes = ", ".join(f"{r['provider']} / {r['model']}" for r in arm["routes"]) or "未观测到模型请求"
        lines.extend(["", f"## {name}", "", f"实际模型：{routes}。", "",
                      f"工具计数：`{json.dumps(arm['tools_by_name'], ensure_ascii=False)}`。", ""])
        if not arm["timeline"]:
            lines.append("尚无工具调用轨迹；请结合运行状态判断是启动失败或仍在等待。")
        else:
            lines.extend(["| 时间（UTC） | 会话 / 步骤 | 工具 | 参数摘要 | 状态 | 记录间隔 s |",
                          "| --- | --- | --- | --- | --- | ---: |"])
            for call in arm["timeline"]:
                status = call["status"]
                if call.get("exit_codes"):
                    status += f"; exit={call['exit_codes']}"
                if call.get("error_code"):
                    status += f"; {call['error_code']}"
                cells = (call["started_at_utc"], f"{call['session_id'][-8:]} / {call['step']}",
                         call["name"], call["arguments_preview"], status,
                         call.get("recorded_duration_seconds", "—"))
                lines.append("| " + " | ".join(markdown_cell(c) for c in cells) + " |")
        failures = [c for c in arm["timeline"] if c["status"] == "failed"]
        if failures:
            lines.extend(["", "失败返回摘要：", ""])
            for call in failures:
                lines.append(f"- 步骤 {call['step']} `{call['name']}`：{call.get('error_preview') or call.get('error_code') or '非零退出'}")
        for session in arm["sessions"]:
            if session["warnings"]:
                lines.extend(["", f"日志读取提示（{session['session_id']}）：", ""])
                lines.extend(f"- {w}" for w in session["warnings"])
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("run_root", type=Path)
    parser.add_argument("--output-dir", type=Path, help="default: run_root")
    args = parser.parse_args()
    root = args.run_root.resolve()
    if not root.is_dir():
        parser.error(f"run directory does not exist: {root}")
    output = (args.output_dir or root).resolve()
    output.mkdir(parents=True, exist_ok=True)
    summary = {
        "schema_version": 1, "run_root": str(root),
        "generated_at_utc": datetime.now(timezone.utc).isoformat(),
        "notes": ["Observable actions only; no reasoning bodies or full tool results exported.",
                  "Run status is the harness process outcome, not scientific validation.",
                  "Token usage sums assistant/message only, excluding inherited session prefixes.",
                  "Parallel tool result timestamps reflect durable model order, not CPU time."],
        "arms": {arm: arm_summary(root, arm) for arm in ("bare", "skill")},
    }
    (output / "trace-summary.json").write_text(json.dumps(summary, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    (output / "flow-trace.md").write_text(markdown(summary), encoding="utf-8")
    print(json.dumps({"output_dir": str(output), "arms": {
        name: {key: arm[key] for key in ("run_status", "steps_started", "tool_calls", "tool_failures", "tokens")}
        for name, arm in summary["arms"].items()}}, ensure_ascii=False))


if __name__ == "__main__":
    main()
